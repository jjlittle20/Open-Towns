package xaos.api.ui;

/**
 * Categories of in-game messages that mods can display.
 */
public enum UiMessageType {

    /**
     * General game/system information.
     */
    SYSTEM,

    /**
     * Important gameplay announcements.
     */
    ANNOUNCEMENT,

    /**
     * Combat-related information.
     */
    COMBAT,

    /**
     * Hero-related information.
     */
    HERO
}