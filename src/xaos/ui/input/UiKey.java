
package xaos.ui.input;

/**
 * Physical keyboard controls understood by
 * the internal UI framework.
 *
 * Printable text is delivered separately
 * through Unicode character events.
 */
public enum UiKey {
    TAB,
    ENTER,
    SPACE,
    BACKSPACE,
    DELETE,
    LEFT,
    RIGHT,
    HOME,
    END,
    ESCAPE
}
