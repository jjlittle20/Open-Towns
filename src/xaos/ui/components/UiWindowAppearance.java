
package xaos.ui.components;

/**
 * Semantic appearance of a UI window.
 *
 * The active theme determines the actual
 * colours, sprites and border treatment.
 */
public enum UiWindowAppearance {

    /**
     * Ordinary framed window or panel.
     */
    STANDARD,

    /**
     * Horizontal gameplay toolbar.
     *
     * The Classic Towns theme uses the
     * original bottom_panel sprite.
     */
    BOTTOM_TOOLBAR
}
